// Generates the gitignored folder-registration indexes. Run by `pre*` npm hooks, build.mjs and the vitest global setup.
//   node scripts/gen-indexes.mjs            write
//   node scripts/gen-indexes.mjs --check    exit 1 when the files on disk differ (never writes)
// Each index lists the *.ts files (not *.test.ts, not starting with _) of an area folder, alphabetically.
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = resolve(dirname(fileURLToPath(import.meta.url)), '..');

const TARGETS = [
  { dir: 'src/content/areas', out: 'src/content/_generated/areas.ts', type: "import type { AreaContent } from '../area';", name: 'AREA_CONTENT', ty: 'readonly AreaContent[]' },
  { dir: 'src/render/textures/areas', out: 'src/render/textures/_generated/areas.ts', type: "import type { PainterSet } from '../canvas';", name: 'AREA_PAINTERS', ty: 'readonly PainterSet[]' },
];

const ident = (f) => 'area_' + f.replace(/\.ts$/, '').replace(/[^A-Za-z0-9]/g, '_');

export function render(t, files) {
  const lines = ['// GENERATED by scripts/gen-indexes.mjs - do not edit, do not commit.', t.type];
  for (const f of files) lines.push(`import ${ident(f)} from '../areas/${f.replace(/\.ts$/, '')}';`);
  lines.push(`export const ${t.name}: ${t.ty} = [${files.map(ident).join(', ')}];`, '');
  return lines.join('\n');
}

export function generate({ root = here, check = false } = {}) {
  const stale = [];
  for (const t of TARGETS) {
    const dir = join(root, t.dir);
    const files = existsSync(dir)
      ? readdirSync(dir).filter((f) => f.endsWith('.ts') && !f.endsWith('.test.ts') && !f.startsWith('_')).sort()
      : [];
    const text = render(t, files);
    const out = join(root, t.out);
    const cur = existsSync(out) ? readFileSync(out, 'utf8') : null;
    if (cur === text) continue;
    if (check) { stale.push(t.out); continue; }
    mkdirSync(dirname(out), { recursive: true });
    writeFileSync(out, text);
  }
  return stale;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check');
  const stale = generate({ check });
  if (stale.length) { console.error('generated indexes out of date: ' + stale.join(', ') + ' (run: node scripts/gen-indexes.mjs)'); process.exit(1); }
}
