// Rebuilds src/render/npcs/artManifest.ts from the PNGs in assets/npcs (docs/api/npcs.md, assets/npcs/README.md):
//
//   node scripts/npc-art.mjs
//
// Each <id>.png (sprite) and <id>_portrait.png found there becomes an import (esbuild inlines it as a data URL); anything missing
// is simply absent from the manifest and the game uses the code-drawn art for that person.
import { existsSync, readdirSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(fileURLToPath(import.meta.url), '../..');
const dir = join(root, 'assets/npcs');
const out = join(root, 'src/render/npcs/artManifest.ts');
const files = existsSync(dir) ? readdirSync(dir).filter((f) => /^[a-z0-9_]+\.(png|jpg|jpeg|webp)$/.test(f)).sort() : [];

const lines = [
  '/** GENERATED by scripts/npc-art.mjs from assets/npcs/*.png. Do not edit. Keys are file names without .png (mara, mara_portrait, ...). */',
];
files.forEach((f, i) => lines.push(`import art${i} from '../../../assets/npcs/${f}';`));
lines.push('', 'export const NPC_ART: Readonly<Record<string, string>> = {');
files.forEach((f, i) => lines.push(`  ${f.replace(/\.(png|jpg|jpeg|webp)$/, '')}: art${i},`));
lines.push('};', '');
writeFileSync(out, lines.join('\n'));
console.log(`npc-art: ${files.length} image${files.length === 1 ? '' : 's'} -> ${out.replace(root, '.')}`);
